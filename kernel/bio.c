// 这里的 buf 用双线链表组织的，这样好实现 LRU 找最近最少使用的缓存。

// 这里为了防止多个进程同时读写一个 buf ，因此给每个 buf 加了一个 sleep lock ，即获取时要保证这个 buf 没有被其他进程获取。



#define NBUCKET 13
#define HASH(id) (id % NBUCKET)

